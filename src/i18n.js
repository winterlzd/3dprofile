export function detectLanguage(languages = []) {
  for (const language of languages) {
    const base = language.toLowerCase().split('-')[0];
    if (base in translations) return base;
  }
  return 'en';
}

export function readPreference(key, fallback) {
  try { return localStorage.getItem(key) || fallback; } catch { return fallback; }
}
export function writePreference(key, value) {
  try { localStorage.setItem(key, value); } catch { /* Private browsing may disable storage. */ }
}

export function applyLanguage(language, root = document) {
  const copy = translations[language] || translations.en;
  document.documentElement.lang = { zh: 'zh-CN', en: 'en', ja: 'ja' }[language] || 'en';
  root.querySelectorAll('[data-i18n]').forEach(el => {
    const value = copy[el.dataset.i18n];
    if (value !== undefined) el.innerHTML = value;
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    const value = copy[el.dataset.i18nTitle];
    if (value !== undefined) { el.title = value; el.setAttribute('aria-label', value); }
  });
  document.title = `${copy.name} · winterlzd`;
  document.querySelector('meta[name="description"]').content = copy.intro.replace(/<br>/g, ' ');
  document.querySelector('meta[property="og:title"]').content = document.title;
  document.querySelector('meta[property="og:description"]').content = copy.intro.replace(/<br>/g, ' ');
  return copy;
}
